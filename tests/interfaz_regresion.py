"""Vistas PHP reales, datos fixture y navegador real. No ejecuta MySQL ni cobra dinero."""
from pathlib import Path
import argparse, base64, json, re, subprocess, tempfile, shutil
from playwright.sync_api import sync_playwright
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--salida',default=str(Path(tempfile.gettempdir())/'fontana-cobro-ui'))
args=parser.parse_args();root=Path(__file__).resolve().parent.parent;out=Path(args.salida).resolve();out.mkdir(parents=True,exist_ok=True)
subprocess.run(['php',str(root/'tests/generar_vistas.php'),str(out/'vistas')],check=True)
def html(file):
    text=(out/'vistas'/file).read_text()
    text=re.sub(r'<link rel="stylesheet" href="([^"]+)">',lambda m:'<style>'+(root/m[1].split('?',1)[0]).read_text()+'</style>',text)
    text=re.sub(r'<script src="([^"]+)" defer></script>',lambda m:'<script>'+(root/m[1].split('?',1)[0]).read_text()+'</script>',text)
    text=re.sub(r'src="(img/[^"]+)"',lambda m:'src="data:image/png;base64,'+base64.b64encode((root/m[1].split('?',1)[0]).read_bytes()).decode()+'"',text)
    return text
results=[];errors=[]
def ok(condition,name):
    assert condition,name
    results.append(name);print('OK',name,flush=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,args=['--no-sandbox'],executable_path=shutil.which('chromium') or shutil.which('chromium-browser'))
    def load(name,width=1440,height=1000):
        page=browser.new_page(viewport={'width':width,'height':height});page.on('pageerror',lambda e:errors.append(str(e)))
        page.set_content(html(name),wait_until='load');return page
    page=load('ventas_base_original.html')
    ok(page.locator('#form-venta').is_visible(),'Base original sin pagos conserva formulario')
    ok(page.locator('#flujo_pago').count()==0,'Sin selector de modalidades en Ventas')
    ok(page.locator('#cobro-overlay').count()==0,'El QR no ocupa la selección de productos')
    ok(page.locator('#normal-confirm').count()==0,'No se exige confirmar dinero antes de mostrar el cobro')
    ok(page.locator('#sale-submit').inner_text()=='Proceder con la venta','Un solo botón para continuar al cobro')
    page.locator('#sale-lines select').select_option('1');page.locator('#sale-lines input[name="cantidad[]"]').fill('2')
    page.locator('#add-line').click();page.locator('#sale-lines select').nth(1).select_option('2');page.locator('#sale-lines input[name="cantidad[]"]').nth(1).fill('3')
    ok(page.locator('#cart-total').inner_text()=='S/ 17.50','Suma de productos exacta S/ 17.50')
    page.locator('#metodo_pago').select_option('Yape')
    ok(page.locator('input[name=recibido]').count()==0,'Yape no obliga a introducir efectivo')
    page.screenshot(path=str(out/'ventas_limpia.png'),full_page=True)
    ok(not re.search(r'\bAPI\b|acad[eé]mic|laboratorio',page.locator('body').inner_text(),re.I),'Pantalla de venta sin API, académico ni laboratorio')
    page.evaluate("document.querySelector('#form-venta').addEventListener('submit',e=>{e.preventDefault();window.sent=new FormData(e.target).get('etapa_venta')})")
    page.locator('#sale-submit').click()
    ok(page.evaluate('window.sent')=='preparar' and page.locator('#sale-submit').is_disabled(),'Continuar solo prepara el cobro y bloquea doble clic')
    page.evaluate("window.dispatchEvent(new Event('pageshow'))")
    ok(page.locator('#sale-submit').is_enabled(),'Volver con historial restaura el botón')
    draft=load('ventas_borrador.html')
    ok(draft.locator('#cart-total').inner_text()=='S/ 17.50' and draft.locator('#sale-lines select').count()==2,'Se recupera el carrito tras validación fallida')
    ok(draft.locator('#numero_documento').get_attribute('maxlength')=='11' and draft.locator('#cliente_nombre').input_value()=='CLIENTE PRUEBA','Se conservan documento y cliente del borrador')
    modal=load('cobro_yape.html')
    ok(modal.locator('#cobro-overlay').is_visible() and modal.locator('#cobro-qr').is_visible(),'QR Yape visible automáticamente al abrir el cobro')
    ok(modal.locator('#cobro-qr').evaluate('img=>img.complete && img.naturalWidth>0'),'QR Izipay cargado correctamente para Yape')
    ok('S/ 17.50' in modal.locator('#cobro-overlay .pago-monto').inner_text(),'La ventana usa el importe preparado por el servidor')
    ok('Mostrar' not in modal.locator('#cobro-overlay').inner_text(),'No existe otro paso Mostrar QR')
    ok(modal.locator('#cobro-referencia').get_attribute('maxlength')=='50','Referencia compatible con columna original de 50 caracteres')
    modal.screenshot(path=str(out/'cobro_yape_automatico.png'))
    modal.evaluate("document.querySelector('#confirmar-cobro-form').addEventListener('submit',e=>{e.preventDefault();window.sent=Object.fromEntries(new FormData(e.target));window.count=(window.count||0)+1})")
    modal.locator('#cobro-referencia').fill('OPER-123');modal.locator('#confirmar-cobro').click()
    data=modal.evaluate('window.sent')
    ok(data['etapa_venta']=='confirmar' and data['confirmado']=='1' and data['referencia_pago']=='OPER-123','Confirmación explícita remite referencia y clave')
    ok(not any(k in data for k in ['total','id_producto','cantidad','metodo_pago']),'Confirmación no remite productos ni importe manipulables')
    ok(modal.locator('#confirmar-cobro').is_disabled() and modal.evaluate('window.count')==1,'Doble envío bloqueado en la ventana de cobro')
    cash=load('cobro_efectivo.html');cash.locator('#cobro-exacto').click()
    ok(cash.locator('#cobro-recibido').input_value()=='17.50','Importe exacto en la ventana de efectivo')
    cash.locator('#cobro-recibido').fill('20')
    ok(cash.locator('#cobro-vuelto').inner_text()=='S/ 2.50','Vuelto visible S/ 2.50 antes de registrar')
    cash.locator('#cobro-recibido').fill('10')
    ok(not cash.locator('#confirmar-cobro-form').evaluate('f=>f.checkValidity()'),'Efectivo insuficiente bloqueado antes del envío')
    plin=load('cobro_plin.html')
    ok(plin.locator('#cobro-qr').is_visible() and plin.locator('#cobro-qr').evaluate('img=>img.complete && img.naturalWidth>0'),'El mismo QR Izipay aparece automáticamente para Plin')
    ok(modal.locator('#cobro-qr').get_attribute('src')==plin.locator('#cobro-qr').get_attribute('src'),'Yape y Plin utilizan exactamente el mismo QR del comercio')
    card=load('cobro_tarjeta.html')
    ok(card.locator('#cobro-qr').count()==0 and 'terminal de tarjetas' in card.locator('#cobro-overlay').inner_text(),'Tarjeta manual muestra instrucciones de terminal, no un QR ajeno')
    expired=load('cobro_vencido.html')
    ok(expired.locator('#confirmar-cobro').count()==0 and expired.locator('#cobro-qr').count()==0,'Un cobro vencido no muestra QR ni botón para confirmar')
    success=load('venta_confirmada.html')
    ok('Venta registrada' in success.locator('#pago-overlay').inner_text() and success.locator('#cobro-qr').count()==0,'Después de confirmar se muestra resultado, no otro QR para cobrar dos veces')
    for width in [360,390]:
        mobile=load('cobro_yape.html',width,844)
        ok(mobile.evaluate('document.documentElement.scrollWidth<=innerWidth') and mobile.locator('.cobro-card').evaluate('(n)=>n.getBoundingClientRect().bottom<=innerHeight'),'Ventana de cobro adaptable a '+str(width)+' px')
        if width==390:mobile.screenshot(path=str(out/'cobro_movil.png'))
    mobile=load('ventas_base_original.html',390,844)
    ok(mobile.evaluate('document.documentElement.scrollWidth<=innerWidth'),'Carrito móvil sin desbordamiento')
    ok(not errors,'Sin excepciones JavaScript en los recorridos probados')
    browser.close()
(out/'resultados.json').write_text(json.dumps({'alcance':'HTML PHP real con datos fixture, SIN MySQL ni API externa','aprobadas':len(results),'casos':results},ensure_ascii=False,indent=2))
print('RESULTADO',len(results),'comprobaciones de interfaz aprobadas')
